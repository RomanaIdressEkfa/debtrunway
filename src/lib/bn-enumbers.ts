/** Bengali words for one additive, falling back to the English entry. */
export function bnAdditive(a: Additive): BnAdditive {
  return BN_ADDITIVES[a.code] ?? { name: a.name, role: a.role, note: a.note };
}

const BN_DIGITS = "০১২৩৪৫৬৭৮৯";

/** ৪৭১ and 471 are the same search, and a Bengali reader will type either. */
export const asciiDigits = (s: string): string =>
  s.replace(/[০-৯]/g, (d) => String(BN_DIGITS.indexOf(d)));

/**
 * Search the Bengali page.
 *
 * The union of what the English search finds and what the Bengali names match,
 * in the list's own order. Union rather than replacement because the thing a
 * Bengali reader is most likely to type is the code itself, copied off a
 * packet printed in English — and "gelatine" should keep working even on the
 * page that calls it জেলাটিন.
 */
export function findAdditivesBn(query: string): Additive[] {
  const raw = asciiDigits(query).trim();
  if (raw === "") return ADDITIVES;

  const byEnglish = new Set(findAdditives(raw).map((a) => a.code));
  const q = raw.toLowerCase().replace(/\s+/g, "");

  return ADDITIVES.filter((a) => {
    if (byEnglish.has(a.code)) return true;
    const bn = BN_ADDITIVES[a.code];
    if (!bn) return false;
    return `${bn.name}${bn.role}`.toLowerCase().replace(/\s+/g, "").includes(q);
  });
}
